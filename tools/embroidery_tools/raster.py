# Working resolution. 0.2 mm per pixel is finer than the machine can resolve
# (min useful stitch is ~1 mm) but keeps mask edges smooth.
MM_PER_PIXEL = 0.2


@dataclass
class TraceSettings:
    size_mm: float | None = None        # longest edge; default = fit the hoop
    colors: int = 5
    density_mm: float = 0.4             # gap between fill rows
    stitch_len_mm: float = 3.0          # max length of one stitch
    # Stitches below this are dropped. Sub-0.5 mm stitches make the needle
    # re-enter almost the same hole while thread is dragged through the eye
    # without advancing — that sawing is a leading cause of thread breaks, and
    # it also draws bobbin thread up to the surface.
    #
    # Read from the machine profile so the tracer, the validator and the
    # Ink/Stitch generators cannot drift apart on the same limit.
    min_stitch_mm: float = field(default_factory=prof.min_stitch_mm)
    # Tie-in / tie-off. Without these every run left by a trim is unanchored and
    # pulls out in wear or the wash; they have to be in the file, the machine
    # will not add them.
    lock_stitches: bool = True
    lock_mm: float = 0.8                # tie leg length (keep under 2 mm)
    min_path_mm: float = 1.5            # a run shorter than this is not worth a trim
    # Stitching pulls fabric inward, so a filled shape finishes narrower than
    # drawn. Growing each colour region slightly compensates, and the side
    # effect is deliberate: adjacent colours overlap instead of leaving a hairline
    # of bare fabric between them. 0.15-0.2 mm is the usual starting point;
    # stretchy knits want more, up to ~0.4 mm.
    pull_comp_mm: float = 0.2
    fill_angle_deg: float = 45.0
    # Tatami stagger: how many rows before the penetration phase repeats.
    # 1 disables it, which lines every row's stitches up into columns — visible
    # as ridges, and a continuous perforation the fabric can tear along.
    stagger_rows: int = 4
    underlay: bool = True
    underlay_density_mm: float = 2.0
    # Pull the underlay in from the edge so the top fill covers it completely.
    # Run to the same boundary and it peeks out along the edges — the "inset"
    # every digitizing package exposes. It also removes a stitch layer from the
    # rim, which is where overlapping passes stack up worst.
    underlay_inset_mm: float = 0.5
    outline: bool = True
    remove_background: bool = True
    bg_tolerance: int = 32
    min_region_mm2: float = 4.0         # drop specks smaller than this
    bridge_mm: float = 0.8              # hops shorter than this skip the trim
    trim_mm: float = 3.0                # only trim when travel exceeds this
    # Walk around holes rather than jump, up to this much travel.
    #
    # Tuned for a machine that does NOT trim jumps within a colour (the SE700
    # does not — you snip each float by hand). Every jump avoided is one fewer
    # float, so the budget is set against hand labour, not machine time. Swept
    # on real artwork (theoretical floor ~145 jumps): 20 mm -> 619 jumps /
    # 41 min snipping; 40 mm -> 281 / 19; 60 mm -> 198 / 13; 90 mm -> 158 / 11.
    # 60 mm reaches ~91% of the floor without piling on detour thread.
    travel_mm: float = 60.0
    # Outline stitch length. Shorter than the fill's, because an outline follows
    # curves and 3 mm chords make them visibly faceted.
    outline_stitch_mm: float = 1.5
    # Ceiling on needle penetrations per mm^2 that TRAVEL may push a cell to.
    #
    # The fill itself sits near 3/mm^2; underlay, outline and colour overlap add
    # a few more. Without a cap, travel routing piled detours onto ground it had
    # already stitched and peaked at 111/mm^2 — dense enough to break thread and
    # needles, which is precisely what the manual warns about ("stitch density
    # that is too fine, or three or more overlapping stitches").
    #
    # This trades directly against jump count and the cliff is sharp: on real
    # artwork, off -> 192 jumps but 111/mm^2 peak; 16 -> 788 jumps and 28 peak.
    # Density wins that argument. A design that snaps thread is unusable; one
    # with more floats is merely tedious to trim. 0 disables the check.
    # Read from the profile so the tracer's cap and the validator's risk line
    # cannot drift apart.
    max_density_per_mm2: float = field(
        default_factory=lambda: float(prof.design_limit("max_density_per_mm2", 16.0)))
    # How hard travel routing steers AROUND ground it has already stitched.
    #
    # This is not a trade-off dial like the cap — a little avoidance improves
    # both numbers at once, because a detour that dodges the busy corridor stays
    # under the density cap and therefore succeeds, instead of being refused and
    # turning back into a float. Measured: 0 -> 750 jumps / 27 peak;
    # 1.0 -> 557 / 22; 3.0 -> 849 / 19; 8.0 -> 1,149 / 17. Past ~1 the detours
    # grow long enough to blow the travel budget, so jumps climb again.
    travel_avoid_weight: float = 1.0
    auto_angle: bool = False            # realigning gave no gain on hole-heavy art
    margin_mm: float = 2.0              # clearance inside the field


@dataclass
class TraceReport:
    layers: list = field(default_factory=list)
    width_mm: float = 0.0
    height_mm: float = 0.0
    total_stitches: int = 0
    dropped_regions: int = 0
    quant_error: float = 0.0
    notes: list = field(default_factory=list)


