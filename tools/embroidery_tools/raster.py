def trace(
    image_path: str | Path,
    output_path: str | Path,
    settings: TraceSettings | None = None,
) -> TraceReport:
    s = settings or TraceSettings()
    image_path, output_path = Path(image_path), Path(output_path)

    img, mm_per_px = _load_and_fit(image_path, s)
    if s.remove_background:
        img = _strip_background(img, s.bg_tolerance)
    img = img.filter(ImageFilter.MedianFilter(3))

    idx, threads, quant_error = _quantise(img, s.colors)

    report = TraceReport()
    report.width_mm = img.width * mm_per_px
    report.height_mm = img.height * mm_per_px
    report.quant_error = round(quant_error, 1)
    if quant_error > 40:
        report.notes.append(
            f"Colour fit is poor (error {quant_error:.0f}/255). This image is "
            f"photographic or heavily shaded — embroidery cannot reproduce it. "
            f"Use flat artwork, or expect a muddy result."
        )
    elif quant_error > 22:
        report.notes.append(
            f"Moderate colour fit (error {quant_error:.0f}/255). Consider more "
            f"--colors, or simplify the artwork."
        )

    spacing_px = s.density_mm / mm_per_px
    underlay_px = s.underlay_density_mm / mm_per_px
    max_len_px = s.stitch_len_mm / mm_per_px
    min_px = int(s.min_region_mm2 / (mm_per_px ** 2))

    pattern = pe.EmbPattern()
    # Centre the design on the origin; the machine centres it in the hoop.
    cx, cy = img.width / 2.0, img.height / 2.0
    break_px = 6.0 / mm_per_px    # travel further than 6 mm -> trim rather than drag
    bridge_px = s.bridge_mm / mm_per_px   # hops this short skip the inside test
    travel_px = s.travel_mm / mm_per_px   # max detour length when routing round a hole

    def to_machine(px_, py_):
        # pyembroidery works in 1/10 mm.
        return ((px_ - cx) * mm_per_px * 10.0, (py_ - cy) * mm_per_px * 10.0)

    # Collect first, write second: one thread and one contiguous block per
    # colour, otherwise every path becomes a colour change and PES overflows its
    # 255-colour-change ceiling.
    # Build every colour's mask first, so pull compensation can be resolved
    # BETWEEN colours before any stitching is planned.
    #
    # Dilating each colour independently makes both sides of a shared boundary
    # claim the same 0.4 mm band, and each lays underlay + fill + outline there.
    # Measured on real artwork: 83% of all over-dense cells — and every one of
    # the eight worst — sat exactly on a colour boundary. The later colour is
    # driving its needle into a band already packed with the earlier colour's
    # thread, which is the manual's "three or more overlapping stitches" and a
    # reliable way to snap needles late in a design.
    #
    # Resolution: the colour stitched LAST owns the seam. Earlier colours are
    # trimmed out of it, so no cell carries two colours' worth of passes, while
    # each colour still pulls outward into bare fabric so no gap opens.
    raw_masks: dict[int, np.ndarray] = {}
    areas: dict[int, float] = {}
    for colour_i in range(len(threads)):
        m = idx == colour_i
        if not m.any():
            continue
        m, dropped = _clean_mask(m, min_px)
        report.dropped_regions += dropped
        if not m.any():
            continue
        areas[colour_i] = float(m.sum()) * mm_per_px ** 2
        grow = int(round(s.pull_comp_mm / mm_per_px))
        raw_masks[colour_i] = (ndimage.binary_dilation(m, iterations=grow)
                               if grow > 0 else m)

    def _luma_of(ci):
        h = threads[ci]["hex"].lstrip("#")
        return (0.2126 * int(h[0:2], 16) + 0.7152 * int(h[2:4], 16)
                + 0.0722 * int(h[4:6], 16))

    stitch_order = sorted(raw_masks, key=_luma_of, reverse=True)
    for pos, ci in enumerate(stitch_order):
        for later in stitch_order[pos + 1:]:
            raw_masks[ci] = raw_masks[ci] & ~raw_masks[later]

    layers: list[tuple[dict, float, list]] = []
    for colour_i in stitch_order:
        mask = raw_masks[colour_i]
        if not mask.any():
            continue
        # Area of the artwork itself, before pull compensation inflated it and
        # before the seam was handed to a later colour.
        area_mm2 = areas[colour_i]

        # Fill each connected shape on its own, in nearest-neighbour order.
        #
        # Sweeping scan lines across the whole colour layer makes every line
        # cross every disconnected shape, so the needle ping-pongs across the
        # design and the trim count explodes — which is what a machine's preview
        # renders as scribble. Filling one shape at a time keeps travel local.
        paths: list[list[tuple[float, float]]] = []
        # One density budget per colour layer, shared across components and
        # across the underlay and fill passes.
        density = _Density(mask.shape, mm_per_px, s.max_density_per_mm2)
        labels, n_comp = ndimage.label(mask)
        components = []
        for comp in range(1, n_comp + 1):
            sub = labels == comp
            ys_, xs_ = np.nonzero(sub)
            components.append((sub, (xs_.mean(), ys_.mean())))

        ordered, remaining = [], list(range(len(components)))
        cur = np.array([0.0, 0.0])
        while remaining:
            j = min(remaining,
                    key=lambda i: (components[i][1][0] - cur[0]) ** 2
                    + (components[i][1][1] - cur[1]) ** 2)
            remaining.remove(j)
            ordered.append(j)
            cur = np.array(components[j][1])

        for j in ordered:
            sub = components[j][0]
            angle = s.fill_angle_deg
            if s.auto_angle:
                angle, _ = _best_fill_angle(sub, spacing_px)

            # Feed ALL fragments of a component through in one call, ordered
            # nearest-neighbour, rather than one call each. Fragments of a
            # component are connected in the mask, so the gap between the end of
            # one and the start of the next is a candidate for travel routing
            # too — calling per fragment forced every one of those gaps to
            # become a jump.
            def _fill_pass(scan_angle, spacing):
                frags = _order_fragments(
                    _scanline_fragments(sub, scan_angle, spacing))
                rows = [row for frag in frags for row in frag]
                if not rows:
                    return []
                return _lines_to_paths(sub, rows, max_len_px, break_px,
                                       bridge_px, travel_px, s.stagger_rows,
                                       density, s.travel_avoid_weight)

            if s.underlay:
                inset = int(round(s.underlay_inset_mm / mm_per_px))
                under_mask = (ndimage.binary_erosion(sub, iterations=inset)
                              if inset > 0 else sub)
                if under_mask.any():
                    outer, sub = sub, under_mask
                    paths += _fill_pass(angle + 90, underlay_px)
                    sub = outer
            paths += _fill_pass(angle, spacing_px)
        # Outline last so it sits over the fill and hides its stepped edges.
        if s.outline:
            outline_step = max(1.0, s.outline_stitch_mm / mm_per_px)
            for contour in _trace_contours(mask):
                pts = _resample_contour(contour, outline_step)
                if len(pts) >= 3:
                    paths.append(pts + [pts[0]])

        # Clean each run, then anchor it. Order matters: filter first so a tie
        # is never built from points the filter would have removed, and drop
        # runs too short to be worth the trim that reaching them costs.
        min_stitch_px = s.min_stitch_mm / mm_per_px
        min_path_px = s.min_path_mm / mm_per_px
        lock_px = s.lock_mm / mm_per_px
        cleaned = []
        for p_ in paths:
            if len(p_) < 2:
                continue
            p_ = _filter_short(p_, min_stitch_px)
            if len(p_) < 2 or _path_length(p_) < min_path_px:
                continue
            if s.lock_stitches:
                p_ = _add_locks(p_, lock_px)
            cleaned.append(p_)
        paths = cleaned
        if paths:
            layers.append((threads[colour_i], area_mm2, paths))

    # Stitch light colours first, dark last.
    #
    # Cluster index order is arbitrary, which left the sequence up to chance.
    # Dark thread covers a light neighbour's edge cleanly; light thread over dark
    # shows every stray dark stitch underneath. Because pull compensation makes
    # neighbouring colours overlap deliberately, whichever colour goes last owns
    # the boundary — so it should be the dark one, which is also usually the
    # outline colour.
    def _luma(layer):
        h = layer[0]["hex"].lstrip("#")
        r, g, b = int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)
        return 0.2126 * r + 0.7152 * g + 0.0722 * b

    layers.sort(key=_luma, reverse=True)

    total_layers = len(layers)
    trim_px = s.trim_mm / mm_per_px
    for li, (thread, area_mm2, paths) in enumerate(layers):
        pattern.add_thread(thread["hex"])
        count = 0
        last_pt = None
        for pi, path in enumerate(paths):
            x0, y0 = to_machine(*path[0])
            if pi:
                # Trim only for real travel; short hops carry the thread.
                #
                # NOTE this has no effect on PES/PEC output. pyembroidery's
                # pec_encode ignores TRIM commands outright and encodes every
                # jump after the first as a trim-jump, so PEC trim count always
                # equals jump count. It does matter for DST and other formats
                # that honour TRIM. The only way to cut trims in a PES is to cut
                # the number of jumps.
                if last_pt is None or math.dist(last_pt, path[0]) > trim_px:
                    pattern.trim()
            pattern.add_stitch_absolute(pe.JUMP, x0, y0)
            for px_, py_ in path:
                mx, my = to_machine(px_, py_)
                pattern.add_stitch_absolute(pe.STITCH, mx, my)
                count += 1
            last_pt = path[-1]
        if li < total_layers - 1:
            pattern.color_change()
        report.layers.append(
            {"thread": thread, "area_mm2": round(area_mm2, 1), "stitches": count}
        )

    if not report.layers:
        raise ValueError(
            "Nothing to stitch. The image may be entirely background, or every "
            "region fell below --min-region."
        )

    pattern.end()
    output_path.parent.mkdir(parents=True, exist_ok=True)
    from . import convert as _convert

    if output_path.suffix.lower() == ".pes":
        # write_pes handles both Brother quirks: the origin convention (PEC
        # coordinates must start at 0,0, not straddle it) and pyembroidery's
        # PES section, which is laid out for a 130x180 hoop.
        _convert.write_pes(pattern, output_path)
    else:
        output_path.parent.mkdir(parents=True, exist_ok=True)
        pe.write(pattern, str(output_path), {})

    report.total_stitches = pattern.count_stitch_commands(pe.STITCH)
    # Report the real stitched extent, not the image canvas — a circle on a
    # square canvas is smaller than the canvas, and the extent is what has to
    # fit the hoop.
    min_x, min_y, max_x, max_y = pattern.bounds()
    report.width_mm = round(prof.units_to_mm(max_x - min_x), 1)
    report.height_mm = round(prof.units_to_mm(max_y - min_y), 1)
    if total_layers >= 6:
        report.notes.append(
            f"{total_layers} colours means {total_layers - 1} manual rethreads."
        )
    return report
