"""Turn a raster image into a stitch plan.

This is an auto-digitizer. Read that word carefully: auto-digitizing is not a
solved problem, and this module is not a substitute for a human digitizer or for
Ink/Stitch's hand-tuned satin columns. What it *is* good at is bold, flat,
few-colour artwork — logos, silhouettes, line art, the kind of thing an AI image
generator produces when you ask it for flat vector art. Feed it a photograph and
you will get a dense unstitchable mess, which is a property of the problem, not
of the implementation.

The pipeline:

    image -> fit to hoop -> strip background -> quantise to N Brother threads
          -> per colour: clean mask -> underlay -> angled scanline fill
          -> contour outline -> EmbPattern -> PES

Design decisions worth knowing:

* Fill is generated by walking scan lines in the *original* coordinate space at
  the requested angle, sampling the mask along each line. Rotating the raster
  instead would resample the mask and chew up thin features.
* Every colour gets one contiguous block, so the machine stops once per colour.
* Underlay runs perpendicular to the top fill. It is what stops the fill sinking
  into the fabric, and it costs about 25% more stitches.
"""

from __future__ import annotations

import heapq
import math
from dataclasses import dataclass, field
from pathlib import Path

