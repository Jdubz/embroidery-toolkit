def _load_and_fit(path: Path, s: TraceSettings) -> tuple[Image.Image, float]:
    """Load, orient, and scale so the design fits the hoop. Returns (rgba, mm/px)."""
    img = Image.open(path)
    try:
        from PIL import ImageOps
        img = ImageOps.exif_transpose(img)
    except Exception:
        pass
    img = img.convert("RGBA")

    field_w, field_h = prof.max_field_mm()
    usable = min(field_w, field_h) - 2 * s.margin_mm
    target_mm = min(s.size_mm, usable) if s.size_mm else usable

    scale = target_mm / max(img.width, img.height)
    px_w = max(1, int(round(img.width * scale / MM_PER_PIXEL)))
    px_h = max(1, int(round(img.height * scale / MM_PER_PIXEL)))
    img = img.resize((px_w, px_h), Image.LANCZOS)
    return img, MM_PER_PIXEL


def _strip_background(img: Image.Image, tol: int) -> Image.Image:
    """Make the background transparent.

    Uses the existing alpha channel when the image has one. Otherwise samples the
    four corners; if they agree, that colour is treated as background and removed
    with a connectivity-aware flood from the border — so an enclosed region of
    the same colour (the hole in a letter 'O' is the usual case) survives.
    """
    arr = np.array(img)
    alpha = arr[:, :, 3]
    if (alpha < 255).mean() > 0.02:
        return img  # already has meaningful transparency

    rgb = arr[:, :, :3].astype(np.int16)
    h, w = rgb.shape[:2]
    corners = np.array(
        [rgb[0, 0], rgb[0, w - 1], rgb[h - 1, 0], rgb[h - 1, w - 1]], dtype=np.int16
    )
    if corners.std(axis=0).max() > tol:
        return img  # corners disagree — no uniform background to strip

    bg = corners.mean(axis=0)
    similar = (np.abs(rgb - bg).max(axis=2) <= tol)

    # Keep only background connected to the border.
    labels, n = ndimage.label(similar)
    if n:
        border = set(labels[0, :]) | set(labels[-1, :]) | set(labels[:, 0]) | set(labels[:, -1])
        border.discard(0)
        outside = np.isin(labels, list(border))
    else:
        outside = np.zeros_like(similar)

    arr[:, :, 3] = np.where(outside, 0, 255).astype(np.uint8)
    return Image.fromarray(arr)


def _quantise(img: Image.Image, n_colors: int) -> tuple[np.ndarray, list[dict]]:
    """Reduce to n_colors and snap each to the nearest Brother thread.

    Returns (index_map, threads) where index_map is -1 for transparent pixels.
    """
    from scipy.cluster.vq import kmeans2

    arr = np.array(img)
    opaque = arr[:, :, 3] > 128
    rgb = arr[:, :, :3].astype(np.float64)

    if not opaque.any():
        raise ValueError("Image is fully transparent after background removal.")

    # Cluster ONLY the opaque pixels. Including the background — even blanked to
    # a filler colour — lets it claim palette slots and silently drop real
    # colours from the design.
    samples = rgb[opaque]
    if len(samples) > 50000:
        step = len(samples) // 50000 + 1
        samples = samples[::step]

    k = min(n_colors, len(np.unique(samples, axis=0)))
    centroids, _ = kmeans2(samples, k, minit="++", seed=0, iter=25)

    # Assign every opaque pixel to its nearest centroid.
    flat = rgb.reshape(-1, 3)
    d = ((flat[:, None, :] - centroids[None, :, :]) ** 2).sum(axis=2)
    idx = d.argmin(axis=1).astype(np.int16).reshape(rgb.shape[:2])
    idx[~opaque] = -1

    # How far the real pixels sit from the colour they were forced into. Flat
    # artwork lands near zero; photographs and gradients score high because no
    # small palette can represent them. This is the honest "is this image
    # suitable" signal, measured rather than guessed.
    assigned = centroids[idx[opaque]]
    quant_error = float(np.sqrt(((rgb[opaque] - assigned) ** 2).sum(axis=1)).mean())

    # Snap each cluster to a Brother thread — and force them to be DISTINCT.
    #
    # This is a correctness requirement, not an aesthetic one. PES merges
    # adjacent blocks that share a colour: write three layers where two share a
    # palette entry and the file reads back as two, so the machine never stops
    # between them and those layers stitch in one pass with one thread. Distinct
    # colours are what create the stops.
    threads = []
    used: set[int] = set()
    for i in range(k):
        r, g, b = (int(round(c)) for c in centroids[i])
        candidates = palette.nearest((r, g, b), 8)
        match = next((c for c in candidates if c["pec_index"] not in used),
                     candidates[0])
        used.add(match["pec_index"])
        threads.append(
            {
                "source_rgb": (r, g, b),
                "hex": match["hex"],
                "name": match["name"],
                "pec_index": match["pec_index"],
                "delta_e": match["delta_e"],
                "substituted": match is not candidates[0],
            }
        )
    return idx, threads, quant_error


def _clean_mask(mask: np.ndarray, min_px: int) -> tuple[np.ndarray, int]:
    """Despeckle and close pinholes. Returns (mask, regions_dropped).

    The opening step erodes then dilates, stripping anything narrower than the
    structuring element. That is what you want against speckle on a blobby mask
    and destructive on line art: a cat drawn in 0.7 mm outline had its face
    shattered from 10 pieces into 26 and stitched out as dashes.

    The guard is on **topology, not area**. Opening is supposed to remove small
    blobs, which lowers the region count; if it raises the count it is breaking
    structures apart instead, so it is discarded. An earlier version tested area
    loss and let this through — the damage was only 2.2% of the mask by area
    while fragmenting the outline into pieces, because a hairline break costs
    almost no pixels.
    """
    mask = ndimage.binary_closing(mask, structure=np.ones((3, 3)))
    opened = ndimage.binary_opening(mask, structure=np.ones((3, 3)))
    if opened.any():
        _, before = ndimage.label(mask)
        _, after = ndimage.label(opened)
        if after <= before:
            mask = opened
    labels, n = ndimage.label(mask)
    if n == 0:
        return mask, 0
    sizes = ndimage.sum(mask, labels, range(1, n + 1))
    keep = np.zeros(n + 1, dtype=bool)
    keep[1:] = sizes >= min_px
    dropped = int((~keep[1:]).sum())
    return keep[labels], dropped


